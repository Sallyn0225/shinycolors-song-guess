/**
 * 计分参数。答对是基础分，剩下的按「认出得有多快」给。
 *
 * 设计意图：让「一听就认出」和「拖到最后一秒蒙对」拉开差距——
 * 猜歌游戏考的是辨识速度，不只是辨识本身。
 */
export const SCORING = {
  /** 答对的基础分。只要答对就一定拿到 */
  base: 100,
  /** 速度奖励上限。宽限期内答对拿满，卡着截止时间答对拿 0 */
  speedBonus: 100,
  /**
   * 速度奖励的宽限期：起播后这么久之内答对，速度分不衰减，之后才开始算。
   *
   * 没有宽限期时最高段位实际不可达——得分率 0.95 要求困难模式 1.6 秒内作答，
   * 而片段有 6 秒，等于只听到四分之一就得点下去。它同时吸收了起播延迟：
   * 计时起点是服务端下发题目的时刻，客户端还要网络往返加解码才真正出声。
   *
   * 1.0 秒试过，只把困难模式门槛推到 2.5 秒，仍偏紧且吃不下起播延迟；1.5 秒放到 2.9 秒
   * （简单模式 2.4 → 3.7 秒）。2.0 秒会放到 3.3 秒，速度分的区分度开始明显变弱。
   * 固定秒数、不随 answerSeconds 按比例缩放——人的反应时间是绝对量，
   * 不会因为限时从 15 秒缩到 10 秒就跟着变短。
   */
  speedGraceSeconds: 1.5,
  /**
   * 速度曲线指数。
   * >1 会让奖励在前段衰减更慢——认出一首歌本来就需要几秒，
   * 线性衰减会让「正常速度答对」显得像失败。1.6 让衰减窗口前 40% 内仍能拿到大部分奖励。
   */
  speedCurve: 1.6,
  /**
   * 每次重听的额外扣分。
   * 重听本身已经在消耗答题时间（倒计时不暂停），这里只再加一点点，
   * 避免「反正时间够，先重听两遍」变成无脑最优解。
   */
  replayPenalty: 10,
} as const

export interface ScoreBreakdown {
  total: number
  base: number
  speed: number
  replayPenalty: number
}
